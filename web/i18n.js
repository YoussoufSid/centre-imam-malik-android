const SKIP = ".notr, .slips, .cards-sheet, .cert, .idcard, #welcome, script, style, textarea";
const ATTRS = ["placeholder", "title", "aria-label"];
/** Translates every text node and common attributes under [root] (browser only). */
export function translateTree(root) {
  if (!root) return;
  const base = root.nodeType === 3 ? root.parentElement : root;
  if (!base || base.closest?.(SKIP)) return;
  if (root.nodeType === 3) { const t = trText(root.nodeValue); if (t !== root.nodeValue) root.nodeValue = t; return; }
  const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let n = w.nextNode(); n; n = w.nextNode()) {
    if (!ARABIC.test(n.nodeValue) || n.parentElement?.closest(SKIP)) continue;
    const t = trText(n.nodeValue); if (t !== n.nodeValue) n.nodeValue = t;
  }
  const els = root.querySelectorAll ? [...root.querySelectorAll("[placeholder],[title],[aria-label]")] : [];
  if (root.matches?.("[placeholder],[title],[aria-label]")) els.push(root);
  for (const el of els) { if (el.closest(SKIP)) continue;
    for (const a of ATTRS) { const v = el.getAttribute(a); if (v && ARABIC.test(v)) { const t = trText(v); if (t !== v) el.setAttribute(a, t); } } }
}

/** Switches the page to French: left-to-right layout, and keeps translating whatever the app draws afterwards. */
export function startFrench() {
  document.documentElement.lang = "fr"; document.documentElement.dir = "ltr";
  document.title = trText(document.title);
  const obs = new MutationObserver((muts) => {
    for (const m of muts) {
      if (m.type === "characterData") translateTree(m.target);
      else m.addedNodes.forEach((n) => { if (n.nodeType === 1 || n.nodeType === 3) translateTree(n); });
    }
  });
  translateTree(document.body);
  obs.observe(document.body, { childList: true, subtree: true, characterData: true });
}
