const ARABIC = /[\u0600-\u06FF]/;
const norm = (s) => s.replace(/\s+/g, " ").trim();
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const LETTER = "[\\u0621-\\u065F\\u0670\\u0671]";   // Arabic letters and diacritics: a phrase must not touch another letter

/** Builds a translator for a phrase dictionary: exact sentence first, then whole-phrase replacement (longest first). */
export function makeTranslator(dict) {
  const entries = Object.entries(dict).map(([k, v]) => [norm(k), v]).sort((a, b) => b[0].length - a[0].length);
  const map = new Map(entries);
  const re = new RegExp(`(?<!${LETTER})(?:${entries.map(([k]) => escRe(k).replace(/ /g, "\\s+")).join("|")})(?!${LETTER})`, "g");
  const cache = new Map();
  return (text) => {
    if (!ARABIC.test(text)) return text;
    if (cache.has(text)) return cache.get(text);
    const lead = text.match(/^\s*/)[0], trail = text.match(/\s*$/)[0], key = norm(text);
    let out = map.has(key) ? map.get(key) : key.replace(re, (m) => map.get(norm(m)) ?? m);
    out = out.replace(/،/g, ",").replace(/؟/g, "?").replace(/؛/g, ";").replace(/٪/g, "%");
    out = lead + out + trail;
    cache.set(text, out); return out;
  };
}

